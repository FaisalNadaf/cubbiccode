/**
 * Explicit registry of every icon the site actually renders.
 *
 * Previously this looked names up in lucide's aggregate `icons` barrel. That
 * barrel is a single runtime object referencing all ~1500 icons, so it defeats
 * tree-shaking (and `optimizePackageImports` cannot help — there is nothing to
 * rewrite). Naming each import lets the bundler drop the rest.
 *
 * It also fixes a silent rendering bug. `AlertTriangle`, `BarChart3`, `Code2`
 * and `LineChart` are deprecated lucide aliases: still exported by name, but
 * absent as keys of `icons`. Every `<Icon name="BarChart3" />` on the site was
 * therefore resolving to `undefined` and rendering nothing.
 *
 * Content files (`src/content/**`, `src/lib/seoClients.ts`) address icons by
 * string name, so adding a new icon there means adding it here too.
 */
