export type IconName = keyof typeof REGISTRY;

export function Icon({ name, ...props }: { name: string } & LucideProps) {
	const LucideIcon = REGISTRY[name as IconName];

	if (!LucideIcon) {
		if (process.env.NODE_ENV !== "production") {
			console.warn(
				`<Icon name="${name}" /> is not in the registry (src/components/ui/Icon.tsx). Nothing will render.`,
			);
		}
		return null;
	}

	return (
		<LucideIcon
			aria-hidden
			{...props}
		/>
	);
}
